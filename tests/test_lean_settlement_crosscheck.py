"""Cross-check the Lean settlement model against the code that runs.

formal/settlement/model_table.json is generated by `lake exe settlement-table`
from the Lean definitions the proofs are about. These tests evaluate the real
implementations on the same inputs:

- moltbook/ledger/mesh_receipt.py split_contribution (the settler's split)
- gpu-mesh/settler/settle.py refusal_status (verifier independence)
- supabase/functions/gpu-mesh splitsClean, decodeSettledLog split_ok,
  checkerPay and independentVerifiers (through Node)

A mismatch is a real divergence between the proved model and deployed code.
"""

from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
from functools import lru_cache
from pathlib import Path

import pytest

from moltbook.ledger.mesh_receipt import MeshReceiptError, split_contribution

ROOT = Path(__file__).resolve().parents[1]
FORMAL = ROOT / "formal" / "settlement"
TABLE = json.loads((FORMAL / "model_table.json").read_text())
MAX_SAFE_INTEGER = 2**53 - 1

SPEC = importlib.util.spec_from_file_location("gpu_mesh_settle_xc", ROOT / "gpu-mesh" / "settler" / "settle.py")
settle = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(settle)


@lru_cache(maxsize=1)
def js() -> dict:
    node = shutil.which("node")
    if not node:
        pytest.skip("node is not installed")
    out = subprocess.run(
        [node, str(FORMAL / "crosscheck" / "eval_js.mjs")],
        check=True,
        capture_output=True,
        text=True,
        cwd=ROOT,
    )
    return json.loads(out.stdout)


def test_table_covers_edge_cases():
    ts = {row["t"] for row in TABLE["split"]}
    assert set(range(241)) <= ts
    assert {1000, 1010, 4000, 19999, 20000, 20001} <= ts
    assert any(t % 20 for t in ts) and any(t and t % 20 == 0 for t in ts)


def test_python_split_matches_model():
    for row in TABLE["split"]:
        t = row["t"]
        try:
            got = list(split_contribution(t))
        except MeshReceiptError:
            got = None
        assert got == row["split"], t


@pytest.mark.parametrize("row", TABLE["split"], ids=lambda r: str(r["t"]))
def test_js_split_matches_model(row):
    # F4 fixed: splitsClean uses exact integer math, so it matches the model
    # on every safe integer, including amounts where t * 9000 passes 2**53.
    got = next(item for item in js()["split"] if item["t"] == row["t"])
    want_clean = row["clean"] if row["t"] <= MAX_SAFE_INTEGER else False
    assert got["clean"] == want_clean


def test_table_covers_float_edge():
    assert any(r["t"] * 9000 > MAX_SAFE_INTEGER and r["clean"] for r in TABLE["split"])
    assert any(r["c"] * 10000 > MAX_SAFE_INTEGER and r["ok"] for r in TABLE["evidence_split_ok"])


def test_mesh_awards_stay_in_safe_range():
    # payWorker pays max(1, completion_tokens) * weight; MAX_TOKENS is 256 and
    # the largest weight is 8, so a contribution is at most 2048 * 1000 units.
    assert 256 * 8 * TABLE["units_per_credit"] * 9000 <= MAX_SAFE_INTEGER


def test_evidence_split_ok_matches_model():
    got = js()["evidence_split_ok"]
    assert len(got) == len(TABLE["evidence_split_ok"])
    for want, have in zip(TABLE["evidence_split_ok"], got, strict=True):
        assert have["ok"] == want["ok"], want


def test_checker_pay_matches_model():
    assert js()["checker_pay"] == TABLE["checker_pay"]


def test_js_independence_matches_model():
    assert js()["independent"] == TABLE["independent"]


def test_js_distinct_payouts_matches_model():
    assert js()["distinct_payouts"] == TABLE["distinct_payouts"]


def test_settler_shared_payout_matches_model():
    worker, v1, v2 = "w", "v1", "v2"
    for row in TABLE["distinct_payouts"]:
        a, b, c = row["addresses"]
        item = {
            "worker_id": worker,
            "verifier1_id": v1,
            "verifier2_id": v2,
            "receipt": {"hash": "x"},
            "worker_address": a,
            "verifier1_address": b,
            "verifier2_address": c,
        }
        status = settle.refusal_status(item)
        if not (a and b and c):
            assert status == "skipped_missing_payout", row
        else:
            assert (status == "skipped_shared_payout") == (not row["distinct"]), row


def test_settler_independence_matches_model():
    for row in TABLE["independent"]:
        item = {
            "worker_id": row["worker"],
            "verifier1_id": row["a"],
            "verifier2_id": row["b"],
            "receipt": {"hash": "x"},
            "worker_address": "0x" + "1" * 40,
            "verifier1_address": "0x" + "2" * 40,
            "verifier2_address": "0x" + "3" * 40,
        }
        refused = settle.refusal_status(item) == "skipped_verifier_independence"
        assert refused == (not row["independent"]), row
