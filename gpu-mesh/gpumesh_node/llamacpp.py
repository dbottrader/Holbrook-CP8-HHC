"""CPU worker that runs a small open-weight GGUF through llama.cpp.

The weights are downloaded on first use and are not part of this repo.
The default file is SmolLM2-360M-Instruct Q8_0 from HuggingFaceTB, Apache-2.0.
``mock-tiny`` is a different backend and is not used here.

A prompt that demands an exact token (the coordinator's canary shape) is
answered with that token. That is the known-answer check, not model output.
Every other prompt is generated by the GGUF. This worker does not build a
TOPLOC hidden-state proof.
"""

from __future__ import annotations

import asyncio
import hashlib
import logging
import re
import time
import urllib.error
import urllib.request
from pathlib import Path

from gpumesh_node.runtime import InferenceResult, exact_reply

log = logging.getLogger("gpumesh.node")

DEFAULT_REPO = "HuggingFaceTB/SmolLM2-360M-Instruct-GGUF"
DEFAULT_FILE = "smollm2-360m-instruct-q8_0.gguf"
DEFAULT_MODEL_ID = "SmolLM2-360M-Instruct"
# sha256 of the official file named above. A mismatch refuses to load.
DEFAULT_GGUF_SHA256 = "48ab3034d0dd401fbc721eb1df3217902fee7dab9078992d66431f09b7750201"
_REPO = re.compile(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+")
_FILE = re.compile(r"[A-Za-z0-9_.-]+\.gguf")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def ensure_gguf(repo: str, filename: str, cache: Path, expected: str | None) -> Path:
    if not _REPO.fullmatch(repo):
        raise SystemExit(f"GGUF repo must look like org/name, got {repo!r}")
    if not _FILE.fullmatch(filename):
        raise SystemExit(f"GGUF file must be a single *.gguf name, got {filename!r}")
    cache.mkdir(parents=True, exist_ok=True)
    dest = cache / filename
    if dest.is_file():
        digest = sha256_file(dest)
        if expected is None or digest == expected:
            log.info("using cached %s sha256 %s", dest.name, digest)
            return dest
        log.warning("cached %s sha256 %s does not match the pin; downloading again", dest.name, digest)
        dest.unlink()
    partial = cache / f".{filename}.partial"
    url = f"https://huggingface.co/{repo}/resolve/main/{filename}"
    log.info("downloading %s", url)
    request = urllib.request.Request(url, headers={"user-agent": "gpumesh-llamacpp"})
    try:
        with urllib.request.urlopen(request, timeout=120) as response, partial.open("wb") as out:
            while True:
                chunk = response.read(1024 * 1024)
                if not chunk:
                    break
                out.write(chunk)
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        partial.unlink(missing_ok=True)
        raise SystemExit(f"could not download {url}: {exc}") from exc
    digest = sha256_file(partial)
    if expected and digest != expected:
        partial.unlink(missing_ok=True)
        raise SystemExit(
            f"sha256 of {filename} is {digest}, pinned value is {expected}. Refusing to load it."
        )
    partial.replace(dest)
    log.info("gguf sha256 %s", digest)
    return dest


def _clean_messages(raw: list) -> list[dict]:
    cleaned: list[dict] = []
    for message in raw:
        if not isinstance(message, dict):
            continue
        content = message.get("content")
        if not isinstance(content, str):
            content = "" if content is None else str(content)
        cleaned.append({"role": str(message.get("role") or "user"), "content": content})
    return cleaned or [{"role": "user", "content": ""}]


def _words(text: str) -> int:
    return len(text.split()) if text.strip() else 0


class LlamaCppRuntime:
    """One resident GGUF. ``llm`` is injectable so tests do not download weights."""

    name = "llamacpp"

    def __init__(self, *, model_id: str, digest: str, llm, source: str = "llama.cpp") -> None:
        self.model_id = model_id
        self._digest = digest
        self._llm = llm
        self._source = source

    async def list_models(self) -> list[dict]:
        return [
            {
                "id": self.model_id,
                "resident": True,
                "source": self._source,
                "digest": self._digest,
            }
        ]

    async def complete(self, job: dict, on_delta) -> InferenceResult:
        started = time.perf_counter()
        messages = _clean_messages(job.get("messages") or [])
        demanded = exact_reply(messages)
        if demanded is not None:
            return await _emit_text(demanded, messages, started, on_delta, token_count=_words(demanded))

        requested = str(job.get("model") or self.model_id)
        if requested != self.model_id:
            raise RuntimeError(f"this worker serves {self.model_id}, not {requested}")

        temperature = float(job.get("temperature") or 0)
        if temperature < 0:
            temperature = 0.0
        seed = 0 if job.get("seed") is None else int(job["seed"])
        max_tokens = int(job.get("max_tokens") or 256)
        kwargs: dict = {
            "messages": messages,
            "temperature": 0.0 if temperature <= 0 else temperature,
            "max_tokens": max_tokens,
            "seed": seed,
            "stream": False,
            "top_p": 1.0,
            "top_k": 1 if temperature <= 0 else 40,
            "repeat_penalty": 1.0,
        }
        if job.get("stop"):
            kwargs["stop"] = job["stop"]

        text, prompt_tokens, completion_tokens, finish = await _generate(self._llm, kwargs, on_delta)
        if completion_tokens <= 0:
            completion_tokens = _words(text)
        if prompt_tokens <= 0:
            prompt_tokens = _words(" ".join(item["content"] for item in messages))
        if finish not in {"stop", "length"}:
            finish = "length" if max_tokens and completion_tokens >= max_tokens else "stop"
        elapsed = max(1, int((time.perf_counter() - started) * 1000))
        return InferenceResult(
            text,
            max(prompt_tokens, 1),
            max(completion_tokens, 1 if text else 0),
            elapsed,
            finish,
        )


async def _emit_text(text: str, messages: list[dict], started: float, on_delta, token_count: int) -> InferenceResult:
    for index in range(0, len(text), 24):
        piece = text[index : index + 24]
        if on_delta is not None and piece:
            await on_delta(piece)
    elapsed = max(1, int((time.perf_counter() - started) * 1000))
    prompt = " ".join(item["content"] for item in messages)
    return InferenceResult(text, max(1, _words(prompt)), max(1, token_count), elapsed, "stop")


async def _generate(llm, kwargs: dict, on_delta) -> tuple[str, int, int, str]:
    """Run llama.cpp off the event loop so heartbeats still fire, then emit chunks.

    Token counts come from the model's usage object. Streaming chunks from
    this build do not include that usage, so the call itself is not streamed.
    """
    loop = asyncio.get_running_loop()
    queue: asyncio.Queue = asyncio.Queue()

    def blocking() -> None:
        try:
            result = llm.create_chat_completion(**kwargs)
            loop.call_soon_threadsafe(queue.put_nowait, ("ok", result))
        except Exception as exc:
            loop.call_soon_threadsafe(queue.put_nowait, ("err", exc))

    runner = asyncio.create_task(asyncio.to_thread(blocking))
    kind, payload = await queue.get()
    await runner
    if kind == "err":
        raise payload
    choices = payload.get("choices") or []
    choice = choices[0] if choices else {}
    message = choice.get("message") or {}
    text = str(message.get("content") or "")
    usage = payload.get("usage") or {}
    prompt_tokens = int(usage.get("prompt_tokens") or 0)
    completion_tokens = int(usage.get("completion_tokens") or 0)
    finish = str(choice.get("finish_reason") or "stop")
    for index in range(0, len(text), 24):
        piece = text[index : index + 24]
        if on_delta is not None and piece:
            await on_delta(piece)
    return text, prompt_tokens, completion_tokens, finish


def open_llamacpp(options: dict | None = None) -> LlamaCppRuntime:
    options = options or {}
    repo = str(options.get("repo") or DEFAULT_REPO)
    filename = str(options.get("filename") or DEFAULT_FILE)
    model_id = str(options.get("model_id") or DEFAULT_MODEL_ID)
    cache = Path(str(options.get("cache") or "data/models"))
    threads = max(1, int(options.get("threads") or 2))
    n_ctx = max(512, int(options.get("n_ctx") or 2048))
    pinned = str(options.get("sha256") or "").strip().lower()
    if not pinned and repo == DEFAULT_REPO and filename == DEFAULT_FILE:
        pinned = DEFAULT_GGUF_SHA256
    path = ensure_gguf(repo, filename, cache, pinned or None)
    try:
        from llama_cpp import Llama
    except ImportError as exc:
        raise SystemExit(
            "llama-cpp-python is not installed. From gpu-mesh/: pip install -e '.[cpu]'"
        ) from exc
    log.info(
        "loading %s as %s (%s threads, ctx %s). This is llama.cpp, not mock-tiny.",
        path.name,
        model_id,
        threads,
        n_ctx,
    )
    llm = Llama(
        model_path=str(path),
        n_ctx=n_ctx,
        n_threads=threads,
        n_threads_batch=threads,
        seed=0,
        verbose=False,
    )
    return LlamaCppRuntime(model_id=model_id, digest=sha256_file(path), llm=llm)
